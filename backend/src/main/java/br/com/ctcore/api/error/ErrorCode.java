package br.com.ctcore.api.error;

import org.springframework.http.HttpStatus;

/** Códigos de erro da API. A mensagem em pt-BR fica em messages.properties (chave {@code error.<CODE>}). */
public enum ErrorCode {
    VALIDATION_ERROR(HttpStatus.BAD_REQUEST),
    MALFORMED_REQUEST(HttpStatus.BAD_REQUEST),
    UNAUTHENTICATED(HttpStatus.UNAUTHORIZED),
    FORBIDDEN(HttpStatus.FORBIDDEN),
    NOT_FOUND(HttpStatus.NOT_FOUND),
    METHOD_NOT_ALLOWED(HttpStatus.METHOD_NOT_ALLOWED),
    CONFLICT(HttpStatus.CONFLICT),
    EDIT_CONFLICT(HttpStatus.CONFLICT),
    PRECONDITION_REQUIRED(HttpStatus.PRECONDITION_REQUIRED),
    UNIT_LIMIT_REACHED(HttpStatus.CONFLICT),
    UNIT_HAS_BLOCKERS(HttpStatus.CONFLICT),
    LAST_UNIT_ADMINISTRATOR(HttpStatus.CONFLICT),
    MODALITY_IN_USE(HttpStatus.CONFLICT),
    MODALITY_NOT_ACTIVE(HttpStatus.CONFLICT),
    REQUEST_ALREADY_OPEN(HttpStatus.CONFLICT),
    ALREADY_IN_CATALOG(HttpStatus.CONFLICT),
    AGE_RANGE_NAME_TAKEN(HttpStatus.CONFLICT),
    STAFF_LIMIT_REACHED(HttpStatus.CONFLICT),
    ALREADY_LINKED(HttpStatus.CONFLICT),
    HAS_PRIMARY_STUDENTS(HttpStatus.CONFLICT),
    UNSUPPORTED_MEDIA_TYPE(HttpStatus.UNSUPPORTED_MEDIA_TYPE),
    INVALID_CREDENTIALS(HttpStatus.UNAUTHORIZED),
    TOO_MANY_REQUESTS(HttpStatus.TOO_MANY_REQUESTS),
    CHALLENGE_FAILED(HttpStatus.BAD_REQUEST),
    INVITE_INVALID(HttpStatus.GONE),
    RESET_LINK_INVALID(HttpStatus.GONE),
    PASSWORD_WEAK(HttpStatus.BAD_REQUEST),
    PASSWORD_LEAKED(HttpStatus.BAD_REQUEST),
    MINOR_HAS_NO_ACCOUNT(HttpStatus.BAD_REQUEST),
    INVALID_TWO_FACTOR_CODE(HttpStatus.UNAUTHORIZED),
    TWO_FACTOR_TICKET_INVALID(HttpStatus.UNAUTHORIZED),
    TWO_FACTOR_SETUP_REQUIRED(HttpStatus.FORBIDDEN),
    REAUTH_REQUIRED(HttpStatus.FORBIDDEN),
    EMAIL_CHANGE_INVALID(HttpStatus.GONE),
    SESSION_CURRENT(HttpStatus.CONFLICT),
    INTERNAL_ERROR(HttpStatus.INTERNAL_SERVER_ERROR);

    public final HttpStatus status;

    ErrorCode(HttpStatus status) {
        this.status = status;
    }
}
